    v_user_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_user_count FROM all_users WHERE username = 'SDUI_ADMIN';
    IF v_user_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE USER sdui_admin IDENTIFIED BY sdui_secret DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP QUOTA UNLIMITED ON USERS';
        EXECUTE IMMEDIATE 'GRANT CONNECT, RESOURCE, CREATE VIEW, CREATE SEQUENCE, CREATE TABLE, CREATE PROCEDURE, UNLIMITED TABLESPACE TO sdui_admin';
    END IF;
END;
