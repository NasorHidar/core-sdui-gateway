-- 1. USERS
CREATE TABLE USERS (
    USR_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_USERS PRIMARY KEY,
    USR_LOGIN_ID      VARCHAR2(255) UNIQUE NOT NULL,
    USR_PASSWORD_HASH VARCHAR2(512) NOT NULL,
    USR_API_TOKEN     VARCHAR2(1024),
    USR_TOKEN_EXPIRY  TIMESTAMP,
    USR_IS_ACTIVE     NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT CHK_USR_IS_ACTIVE CHECK (USR_IS_ACTIVE IN (0, 1)),
    USR_CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 2. SERVICE
CREATE TABLE SERVICE (
    SVR_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_SERVICE PRIMARY KEY,
    SVR_NAME         VARCHAR2(255) NOT NULL,
    SVR_ICON_URL     VARCHAR2(512),
    SVR_BASE_API_URL VARCHAR2(512) NOT NULL,
    SVR_IS_ACTIVE    NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT CHK_SVR_IS_ACTIVE CHECK (SVR_IS_ACTIVE IN (0, 1)),
    SVR_SORT_ORDER   NUMBER DEFAULT 1
);

-- 3. SERVICE_DETAILS
CREATE TABLE SERVICE_DETAILS (
    SVRD_MENU_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_SERVICE_DETAILS PRIMARY KEY,
    SVR_ID              NUMBER NOT NULL,
    SVRD_PARENT_MENU_ID NUMBER DEFAULT NULL,
    SVRD_DISPLAY_ORDER  NUMBER DEFAULT 1,
    SVRD_MENU_NAME      VARCHAR2(255) NOT NULL,
    SVRD_MENU_CODE      VARCHAR2(64),
    SVRD_MENU_URL       VARCHAR2(512),
    SVRD_MENU_TYPE      VARCHAR2(64) DEFAULT 'MENU' NOT NULL,
    SVRD_ALLOWED_ROLES  VARCHAR2(512),
    SVRD_PAGE_ID        NUMBER,
    SVRD_IS_ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT CHK_SVRD_IS_ACTIVE CHECK (SVRD_IS_ACTIVE IN (0, 1)),
    SVRD_CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 4. PAGE_TEMPLATE
CREATE TABLE PAGE_TEMPLATE (
    PAGE_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_PAGE_TEMPLATE PRIMARY KEY,
    PAGE_TITLE         VARCHAR2(255) NOT NULL,
    PAGE_LAYOUT_TYPE   VARCHAR2(64) NOT NULL,
    PAGE_UI_BLUEPRINT  JSON NOT NULL,
    PAGE_CUSTOM_JS_URL VARCHAR2(512),
    PAGE_VERSION       VARCHAR2(32) DEFAULT 'v1.0.0' NOT NULL
);

-- 5. PAGE_ACTION
CREATE TABLE PAGE_ACTION (
    ACT_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_PAGE_ACTION PRIMARY KEY,
    SVRD_MENU_ID        NUMBER NOT NULL,
    ACT_NAME            VARCHAR2(255) NOT NULL,
    ACT_TYPE            VARCHAR2(64) NOT NULL,
    ACT_HTTP_METHOD     VARCHAR2(16) DEFAULT 'POST',
    ACT_TARGET_ENDPOINT VARCHAR2(512),
    ACT_TARGET_WIDGET   VARCHAR2(255),
    ACT_JSON_SCHEMA     JSON,
    ACT_VISIBILITY_RULE JSON,
    ACT_DISPLAY_ORDER   NUMBER DEFAULT 1
);

-- 6. BUSINESS_LOGIC_CONFIG
CREATE TABLE BUSINESS_LOGIC_CONFIG (
    BL_ID               NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_BUSINESS_LOGIC_CONFIG PRIMARY KEY,
    ACT_ID              NUMBER NOT NULL,
    BL_IDENTIFIER       VARCHAR2(255) NOT NULL,
    BL_EXECUTION_PARAMS JSON
);

-- 7. LOGIN_LOG
CREATE TABLE LOGIN_LOG (
    LLOG_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_LOGIN_LOG PRIMARY KEY,
    USR_ID          NUMBER NOT NULL,
    LLOG_IP_ADDRESS VARCHAR2(64),
    LLOG_USER_AGENT VARCHAR2(512),
    LLOG_STATUS     VARCHAR2(64) NOT NULL,
    LLOG_CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 8. ACTIVITY_LOG
CREATE TABLE ACTIVITY_LOG (
    ACT_LOG_ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_ACTIVITY_LOG PRIMARY KEY,
    ACT_LOG_EVENT_ID       VARCHAR2(64) NOT NULL,
    ACT_LOG_USER_ID        VARCHAR2(64) NOT NULL,
    ACT_LOG_ACTION         VARCHAR2(256) NOT NULL,
    ACT_LOG_REFERENCE_KEY  VARCHAR2(256),
    ACT_LOG_PAYLOAD        CLOB,
    ACT_LOG_SOURCE_IP      VARCHAR2(64),
    ACT_LOG_CREATED_AT     TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL
);

